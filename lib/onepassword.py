# (c) Martin Erzberger 2026
# Wrapper for the 1Password CLI (op).
# Every private key password is a Password item in one vault, titled after the key:
# root-ca, issuing-ca, and <cert_name> for issued certificates.

import json
import os
import shutil
import subprocess

from .common import HomeCAError, config

TAG = 'home-ca'


def _vault():
    vault = config().onepassword_vault
    if not vault:
        raise HomeCAError('onepassword.vault is not set in lib/defaults.yaml.')
    return vault


def _op(*args):
    """Run op and return stdout; raise HomeCAError with a readable message on failure."""
    if shutil.which('op') is None:
        raise HomeCAError('1Password CLI (op) not found. Install it: brew install 1password-cli')
    # No stdin: op item create/edit would read piped input as a JSON item template
    result = subprocess.run(['op', *args], capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if result.returncode != 0:
        raise HomeCAError(
            f'1Password CLI failed: op {" ".join(args[:2])}\n'
            f'  {result.stderr.strip()}\n'
            'Make sure the 1Password app is unlocked and CLI integration is enabled.'
        )
    return result.stdout


def item_exists(title):
    items = json.loads(_op('item', 'list', '--vault', _vault(), '--format', 'json'))
    count = sum(item['title'] == title for item in items)
    if count > 1:
        raise HomeCAError(f'{count} items named "{title}" in vault "{_vault()}". Remove the duplicates.')
    return count == 1


def _password_of(item, what):
    password = next((f.get('value') for f in item.get('fields', []) if f.get('id') == 'password'), None)
    if not password:
        raise HomeCAError(f'1Password returned no password for {what}. Unlock 1Password and retry.')
    return password


def read_password(title):
    """Return the password of item <title> in the configured vault."""
    password = _op('read', '--no-newline', f'op://{_vault()}/{title}/password')
    if not password:
        raise HomeCAError(f'1Password returned an empty password for "{title}". Unlock 1Password and retry.')
    return password


def create_password_item(title, note):
    """Create a Password item with a generated password and return the password.

    The password is generated by 1Password, so it never appears on a command line.
    """
    item = json.loads(_op('item', 'create', '--category', 'password', '--vault', _vault(),
                          '--title', title, '--tags', TAG,
                          '--generate-password=letters,digits,40',
                          f'notesPlain={note}', '--format', 'json'))
    return _password_of(item, f'the new item "{title}"')


def read_login(reference):
    """(username, password, one-time password or None) of a login item, e.g. op://Private/NAS."""
    vault, title = reference.removeprefix('op://').split('/', 1)
    item = json.loads(_op('item', 'get', title, '--vault', vault, '--format', 'json'))
    fields = item.get('fields', [])
    username = next((f.get('value') for f in fields if f.get('id') == 'username'), None)
    otp = next((f.get('totp') for f in fields if f.get('type') == 'OTP'), None)
    if not username:
        raise HomeCAError(f'1Password item {reference} has no username.')
    return username, _password_of(item, reference), otp


def attach_file(title, path):
    """Attach the file at path to item <title>, replacing an attachment of the same name."""
    name = os.path.basename(path).replace('.', r'\.')   # '.' would start a section name
    _op('item', 'edit', title, '--vault', _vault(), f'{name}[file]={os.path.abspath(path)}')


def read_file(title, name, out_path, vault=None):
    """Save the attachment <name> of item <title> to out_path. vault defaults to the
    configured one; pass it when lib/defaults.yaml is not available (restore)."""
    vault = vault or _vault()
    item = json.loads(_op('item', 'get', title, '--vault', vault, '--format', 'json'))
    ids = [f['id'] for f in item.get('files', []) if f.get('name') == name]
    if not ids:
        raise HomeCAError(f'Item "{title}" in vault "{vault}" has no attachment "{name}".')
    _op('read', '--force', '--out-file', out_path, f'op://{vault}/{item["id"]}/{ids[0]}')
