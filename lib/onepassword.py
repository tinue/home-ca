# Wrapper for the 1Password CLI (op).
# Every private key password is a Password item in one vault, titled after the key:
# root-ca, issuing-ca, and <cert_name> for issued certificates.

import json
import os
import shutil
import subprocess
import sys

TAG = 'home-ca'


def setup():
    global variables
    from .common import setup
    variables = setup()


def _vault():
    setup()
    if not variables.onepassword_vault:
        sys.exit('onepassword.vault is not set in lib/defaults.yaml.')
    return variables.onepassword_vault


def _op(*args):
    """Run op and return stdout; exit with a readable message on failure."""
    if shutil.which('op') is None:
        sys.exit('1Password CLI (op) not found. Install it: brew install 1password-cli')
    # No stdin: op item create/edit would read piped input as a JSON item template
    result = subprocess.run(['op', *args], capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if result.returncode != 0:
        sys.exit(
            f'1Password CLI failed: op {" ".join(args[:2])}\n'
            f'  {result.stderr.strip()}\n'
            'Make sure the 1Password app is unlocked and CLI integration is enabled.'
        )
    return result.stdout


def _item_ids(title):
    items = json.loads(_op('item', 'list', '--vault', _vault(), '--format', 'json'))
    return [item['id'] for item in items if item['title'] == title]


def item_exists(title):
    ids = _item_ids(title)
    if len(ids) > 1:
        sys.exit(f'{len(ids)} items named "{title}" in vault "{_vault()}". Remove the duplicates.')
    return bool(ids)


def read_password(title):
    """Return the password of item <title> in the configured vault."""
    if not item_exists(title):
        sys.exit(f'No item "{title}" in 1Password vault "{_vault()}".')
    password = _op('read', '--no-newline', f'op://{_vault()}/{title}/password')
    if not password:
        sys.exit(f'1Password returned an empty password for "{title}". Unlock 1Password and retry.')
    return password


def create_password_item(title, note):
    """Create a Password item with a generated password and return the password.

    The password is generated by 1Password, so it never appears on a command line.
    """
    if item_exists(title):
        sys.exit(f'Item "{title}" already exists in vault "{_vault()}".')
    _op('item', 'create', '--category', 'password', '--vault', _vault(),
        '--title', title, '--tags', TAG,
        '--generate-password=letters,digits,40',
        f'notesPlain={note}', '--format', 'json')
    return read_password(title)


def read_field(reference):
    """Read any secret reference, e.g. op://Private/NAS/username."""
    value = _op('read', '--no-newline', reference)
    if not value:
        sys.exit(f'1Password returned an empty value for {reference}. Unlock 1Password and retry.')
    return value


def read_otp(item_reference):
    """Current one-time password of an item (op://vault/item), or None if it has none."""
    vault, item = item_reference.removeprefix('op://').split('/', 1)
    result = subprocess.run(['op', 'item', 'get', item, '--vault', vault, '--otp'],
                            capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else None


def attach_file(title, path):
    """Attach the file at path to item <title>, replacing an attachment of the same name."""
    if not item_exists(title):
        sys.exit(f'No item "{title}" in 1Password vault "{_vault()}".')
    name = os.path.basename(path).replace('.', r'\.')   # '.' would start a section name
    _op('item', 'edit', title, '--vault', _vault(), f'{name}[file]={os.path.abspath(path)}')


def read_file(title, name, out_path, vault=None):
    """Save the attachment <name> of item <title> to out_path. vault defaults to the
    configured one; pass it when lib/defaults.yaml is not available (restore)."""
    vault = vault or _vault()
    item = json.loads(_op('item', 'get', title, '--vault', vault, '--format', 'json'))
    ids = [f['id'] for f in item.get('files', []) if f.get('name') == name]
    if not ids:
        sys.exit(f'Item "{title}" in vault "{vault}" has no attachment "{name}".')
    _op('read', '--force', '--out-file', out_path, f'op://{vault}/{item["id"]}/{ids[0]}')
